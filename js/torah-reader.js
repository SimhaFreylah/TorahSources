/* =========================================================
   3. ИВРИТСКИЙ НОМЕР ГЛАВЫ

   Преобразует:

       1  → א
       2  → ב
       10 → י
       11 → יא
       20 → כ
       50 → נ

   Особые традиционные формы:

       15 → טו
       16 → טז
   ========================================================= */

function toHebrewNumber(number) {


    /* ---------------------------------------------------------
       ЕДИНИЦЫ
       --------------------------------------------------------- */

    const ones = [
        "",
        "א",
        "ב",
        "ג",
        "ד",
        "ה",
        "ו",
        "ז",
        "ח",
        "ט"
    ];


    /* ---------------------------------------------------------
       ДЕСЯТКИ

       10 = י
       20 = כ
       30 = ל
       40 = מ
       50 = נ
       --------------------------------------------------------- */

    const tens = [
        "",
        "י",
        "כ",
        "ל",
        "מ",
        "נ"
    ];


    /* ---------------------------------------------------------
       ОСОБЫЙ СЛУЧАЙ — 15
       --------------------------------------------------------- */

    if (number === 15) {

        return "טו";

    }


    /* ---------------------------------------------------------
       ОСОБЫЙ СЛУЧАЙ — 16
       --------------------------------------------------------- */

    if (number === 16) {

        return "טז";

    }


    /* ---------------------------------------------------------
       ОПРЕДЕЛЯЕМ ДЕСЯТКИ

       Например:
       23 → 2
       --------------------------------------------------------- */

    const ten =
        Math.floor(
            number / 10
        );


    /* ---------------------------------------------------------
       ОПРЕДЕЛЯЕМ ЕДИНИЦЫ

       Например:
       23 → 3
       --------------------------------------------------------- */

    const one =
        number % 10;


    /* ---------------------------------------------------------
       СОЕДИНЯЕМ

       23:
       כ + ג = כג
       --------------------------------------------------------- */

    return (
        (tens[ten] || "") +
        (ones[one] || "")
    );

}


/* =========================================================
   4. ДВУХЗНАЧНЫЙ НОМЕР ФАЙЛА

   Преобразует:

       1  → 01
       2  → 02
       9  → 09
       10 → 10
       25 → 25

   Используется при формировании:

       bereshit-01.html
       bereshit-02.html
       bereshit-10.html
   ========================================================= */

function formatChapterFileNumber(chapter) {

    return String(chapter).padStart(
        2,
        "0"
    );

}


/* =========================================================
   5. ПАРАМЕТРЫ URL

   Читает:

       ?book=bereshit&chapter=1

   Получаем:

       book = bereshit
       chapter = 1

   Если параметры неправильные,
   используются безопасные значения.
   ========================================================= */

function getParams() {


    /* ---------------------------------------------------------
       ПОЛУЧАЕМ URL-ПАРАМЕТРЫ
       --------------------------------------------------------- */

    const params =
        new URLSearchParams(
            window.location.search
        );


    /* ---------------------------------------------------------
       КНИГА

       Если параметр отсутствует:
       открываем Берешит.
       --------------------------------------------------------- */

    let book =
        params.get("book") ||
        "bereshit";


    /* ---------------------------------------------------------
       ГЛАВА

       parseInt превращает:
       "5" → 5
       --------------------------------------------------------- */

    let chapter =
        parseInt(
            params.get("chapter"),
            10
        ) || 1;


    /* ---------------------------------------------------------
       ПРОВЕРЯЕМ КНИГУ
       --------------------------------------------------------- */

    if (!books[book]) {

        book =
            "bereshit";

    }


    /* ---------------------------------------------------------
       ПРОВЕРЯЕМ НОМЕР ГЛАВЫ
       --------------------------------------------------------- */

    if (
        chapter < 1 ||
        chapter > books[book].chapters
    ) {

        chapter =
            1;

    }


    /* ---------------------------------------------------------
       ВОЗВРАЩАЕМ ПРОВЕРЕННЫЕ ДАННЫЕ
       --------------------------------------------------------- */

    return {
        book,
        chapter
    };

}


/* =========================================================
   6. ПУТЬ К ФАЙЛУ ГЛАВЫ

   Структура:

       torah/
       │
       ├── reader.html
       │
       ├── 01_bereshit/
       │   ├── bereshit-01.html
       │   ├── bereshit-02.html
       │   └── ...
       │
       ├── 02_shemot/
       ├── 03_vayikra/
       ├── 04_bemidbar/
       └── 05_devarim/

   Например:

       book = bereshit
       chapter = 1

   Получаем:

       01_bereshit/bereshit-01.html
   ========================================================= */

function getChapterFilePath(
    book,
    chapter
) {


    /* ---------------------------------------------------------
       ДАННЫЕ КНИГИ
       --------------------------------------------------------- */

    const bookData =
        books[book];


    /* ---------------------------------------------------------
       ДВУХЗНАЧНЫЙ НОМЕР ГЛАВЫ

       1 → 01
       --------------------------------------------------------- */

    const chapterNumber =
        formatChapterFileNumber(
            chapter
        );


    /* ---------------------------------------------------------
       ПАПКА reader.html
       --------------------------------------------------------- */

    const readerFolder =
        new URL(
            "./",
            window.location.href
        );


    /* ---------------------------------------------------------
       ФОРМИРУЕМ URL ФАЙЛА
       --------------------------------------------------------- */

    const chapterUrl =
        new URL(
            `${bookData.folder}/${book}-${chapterNumber}.html`,
            readerFolder
        );


    return chapterUrl.href;

}


/* =========================================================
   7. ЗАГОЛОВОК ГЛАВЫ

   Создаёт:

       Берешит 1 | בראשית א

   Также меняет название вкладки браузера:

       Берешит 1 | בראשית א | TorahSources

   Одновременно обновляет компактный
   sticky-заголовок.
   ========================================================= */

function renderChapterTitle(
    book,
    chapter
) {


    /* ---------------------------------------------------------
       ПОЛУЧАЕМ ДАННЫЕ КНИГИ
       --------------------------------------------------------- */

    const bookData =
        books[book];


    /* ---------------------------------------------------------
       ОЧИЩАЕМ ПРЕДЫДУЩИЙ ЗАГОЛОВОК
       --------------------------------------------------------- */

    chapterTitle.innerHTML =
        "";


    /* ---------------------------------------------------------
       7.1. РУССКАЯ ЧАСТЬ

       Например:
       Шмот 16
       --------------------------------------------------------- */

    const titleRu =
        document.createElement(
            "span"
        );


    titleRu.className =
        "title-ru";


    titleRu.textContent =
        `${bookData.name} ${chapter}`;


    /* ---------------------------------------------------------
       7.2. РАЗДЕЛИТЕЛЬ
       --------------------------------------------------------- */

    const separator =
        document.createElement(
            "span"
        );


    separator.className =
        "title-separator";


    separator.textContent =
        " | ";


    /* ---------------------------------------------------------
       7.3. ИВРИТСКАЯ ЧАСТЬ

       Например:
       שמות טז
       --------------------------------------------------------- */

    const titleHe =
        document.createElement(
            "span"
        );


    titleHe.className =
        "title-he";


    titleHe.lang =
        "he";


    titleHe.dir =
        "rtl";


    titleHe.textContent =
        `${bookData.heName} ${toHebrewNumber(chapter)}`;


    /* ---------------------------------------------------------
       7.4. ДОБАВЛЯЕМ ЗАГОЛОВОК В HTML
       --------------------------------------------------------- */

    chapterTitle.appendChild(
        titleRu
    );


    chapterTitle.appendChild(
        separator
    );


    chapterTitle.appendChild(
        titleHe
    );


    /* ---------------------------------------------------------
       7.5. ОБНОВЛЯЕМ STICKY-ЗАГОЛОВОК
       --------------------------------------------------------- */

    if (
        stickyChapterRu &&
        stickyChapterHe
    ) {

        stickyChapterRu.textContent =
            `${bookData.name} ${chapter}`;


        stickyChapterHe.textContent =
            `${bookData.heName} ${toHebrewNumber(chapter)}`;

    }


    /* ---------------------------------------------------------
       7.6. ЗАГОЛОВОК ВКЛАДКИ БРАУЗЕРА
       --------------------------------------------------------- */

    document.title =
        `${bookData.name} ${chapter} | ` +
        `${bookData.heName} ${toHebrewNumber(chapter)} | ` +
        `TorahSources`;

}


/* =========================================================
   7A. STICKY-ЗАГОЛОВОК ГЛАВЫ

   Пока большой заголовок главы виден,
   компактная полоса скрыта.

   После того как большой заголовок
   полностью уходит вверх, появляется:

       Шмот 16 | שמות טז

   Проверка работает:

   - при прокрутке правой панели на компьютере;
   - при обычной прокрутке страницы на мобильном.
   ========================================================= */


/* =========================================================
   СКРЫВАЕМ STICKY-ЗАГОЛОВОК
   ========================================================= */

function hideStickyChapterHeader() {


    if (!stickyChapterHeader) {

        return;

    }


    stickyChapterHeader.classList.remove(
        "is-visible"
    );


    stickyChapterHeader.setAttribute(
        "aria-hidden",
        "true"
    );

}


/* =========================================================
   ПОКАЗЫВАЕМ STICKY-ЗАГОЛОВОК
   ========================================================= */

function showStickyChapterHeader() {


    if (!stickyChapterHeader) {

        return;

    }


    stickyChapterHeader.classList.add(
        "is-visible"
    );


    stickyChapterHeader.setAttribute(
        "aria-hidden",
        "false"
    );

}


/* =========================================================
   ПРОВЕРЯЕМ ПОЛОЖЕНИЕ БОЛЬШОГО ЗАГОЛОВКА
   ========================================================= */

function updateStickyChapterHeaderVisibility() {


    if (
        !chapterTitle ||
        !stickyChapterHeader ||
        !torahContentPanel
    ) {

        return;

    }


    /* ---------------------------------------------------------
       ПОЛОЖЕНИЕ БОЛЬШОГО ЗАГОЛОВКА
       ОТНОСИТЕЛЬНО ОКНА БРАУЗЕРА
       --------------------------------------------------------- */

    const titleRect =
        chapterTitle.getBoundingClientRect();


    /* ---------------------------------------------------------
       ПОЛОЖЕНИЕ ПРАВОЙ ПАНЕЛИ
       --------------------------------------------------------- */

    const panelRect =
        torahContentPanel.getBoundingClientRect();


    /* ---------------------------------------------------------
       ВЕРХНЯЯ ВИДИМАЯ ГРАНИЦА

       На компьютере используется верх панели.

       На мобильном, когда прокручивается вся страница,
       используется верх окна браузера.
       --------------------------------------------------------- */

    const visibleTop =
        Math.max(
            panelRect.top,
            0
        );


    /* ---------------------------------------------------------
       ЕСЛИ БОЛЬШОЙ ЗАГОЛОВОК УШЁЛ ВВЕРХ
       --------------------------------------------------------- */

    if (
        titleRect.bottom <= visibleTop
    ) {

        showStickyChapterHeader();

    } else {

        hideStickyChapterHeader();

    }

}


