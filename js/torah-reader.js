/* =========================================================
   8. АКТИВНАЯ КНИГА

   Подсвечивает выбранную книгу.

   Например:

       data-book="shemot"

   получает класс:

       active-book
   ========================================================= */

function setActiveBook(book) {


    bookLinks.forEach(
        link => {


            /* -------------------------------------------------
               ССЫЛКА СООТВЕТСТВУЕТ ТЕКУЩЕЙ КНИГЕ
               ------------------------------------------------- */

            if (
                link.dataset.book === book
            ) {

                link.classList.add(
                    "active-book"
                );

            } else {

                link.classList.remove(
                    "active-book"
                );

            }

        }
    );

}


/* =========================================================
   9. СПИСОК ГЛАВ

   Автоматически создаёт:

       1
       2
       3
       4
       ...

   Для каждой книги количество глав
   берётся из:

       books[book].chapters
   ========================================================= */

function renderChapters(book) {


    /* ---------------------------------------------------------
       УДАЛЯЕМ СТАРЫЙ СПИСОК
       --------------------------------------------------------- */

    chapterList.innerHTML =
        "";


    /* ---------------------------------------------------------
       КОЛИЧЕСТВО ГЛАВ
       --------------------------------------------------------- */

    const totalChapters =
        books[book].chapters;


    /* ---------------------------------------------------------
       СОЗДАЁМ КНОПКУ ДЛЯ КАЖДОЙ ГЛАВЫ
       --------------------------------------------------------- */

    for (
        let chapter = 1;
        chapter <= totalChapters;
        chapter++
    ) {


        /* -----------------------------------------------------
           9.1. СОЗДАЁМ ССЫЛКУ
           ----------------------------------------------------- */

        const link =
            document.createElement(
                "a"
            );


        /* -----------------------------------------------------
           НАСТОЯЩИЙ URL ССЫЛКИ

           Например:

           ?book=shemot&chapter=16
           ----------------------------------------------------- */

        link.href =
            `?book=${book}&chapter=${chapter}`;


        /* -----------------------------------------------------
           НОМЕР ГЛАВЫ
           ----------------------------------------------------- */

        link.textContent =
            chapter;


        /* -----------------------------------------------------
           DATA-АТРИБУТ
           ----------------------------------------------------- */

        link.dataset.chapter =
            chapter;


        /* -----------------------------------------------------
           9.2. АКТИВНАЯ ГЛАВА
           ----------------------------------------------------- */

        if (
            chapter === currentChapter
        ) {

            link.classList.add(
                "active-chapter"
            );

        }


        /* -----------------------------------------------------
           9.3. НАЖАТИЕ НА ГЛАВУ
           ----------------------------------------------------- */

        link.addEventListener(
            "click",
            function (event) {


                /* Отменяем обычную перезагрузку страницы */

                event.preventDefault();


                /* Загружаем главу динамически */

                loadChapter(
                    book,
                    chapter,
                    true
                );

            }
        );


        /* -----------------------------------------------------
           9.4. ДОБАВЛЯЕМ ССЫЛКУ В СПИСОК
           ----------------------------------------------------- */

        chapterList.appendChild(
            link
        );

    }

}


/* =========================================================
   10. ЗАГРУЗКА ГЛАВЫ

   Главная функция ридера.

   Выполняет:

   1. Проверку книги.
   2. Проверку главы.
   3. Запоминание состояния.
   4. Возврат прокрутки наверх.
   5. Подсветку книги.
   6. Создание списка глав.
   7. Создание заголовка.
   8. Формирование пути.
   9. Загрузку HTML.
   10. Вставку HTML.
   11. Обновление URL.

   pushState:

       false
       URL не добавляется в историю.

       true
       новый URL добавляется в историю браузера.
   ========================================================= */

async function loadChapter(
    book,
    chapter,
    pushState = false
) {


    /* ---------------------------------------------------------
       10.1. ПРОВЕРКА КНИГИ
       --------------------------------------------------------- */

    if (!books[book]) {


        /* Если книги нет —
           возвращаемся к Берешит */

        book =
            "bereshit";

    }


    /* ---------------------------------------------------------
       10.2. ПРОВЕРКА НОМЕРА ГЛАВЫ
       --------------------------------------------------------- */

    if (
        chapter < 1 ||
        chapter > books[book].chapters
    ) {


        /* Если номер неправильный —
           открываем первую главу */

        chapter =
            1;

    }


    /* ---------------------------------------------------------
       10.3. ЗАПОМИНАЕМ ТЕКУЩЕЕ СОСТОЯНИЕ
       --------------------------------------------------------- */

    currentBook =
        book;


    currentChapter =
        chapter;


    /* ---------------------------------------------------------
       ВОЗВРАЩАЕМ ТЕКСТ К НАЧАЛУ НОВОЙ ГЛАВЫ
       --------------------------------------------------------- */

    if (torahContentPanel) {

        torahContentPanel.scrollTop =
            0;

    }


    /*
       На мобильной версии может прокручиваться
       уже сама страница.
    */

    window.scrollTo(
        {
            top: 0,
            behavior: "auto"
        }
    );


    /* ---------------------------------------------------------
       СКРЫВАЕМ STICKY-ЗАГОЛОВОК
       ДО НАЧАЛА НОВОЙ ПРОКРУТКИ
       --------------------------------------------------------- */

    hideStickyChapterHeader();


    /* ---------------------------------------------------------
       10.4. ОБНОВЛЯЕМ ИНТЕРФЕЙС
       --------------------------------------------------------- */


    /* ---------------------------------------------------------
       ПОДСВЕЧИВАЕМ КНИГУ
       --------------------------------------------------------- */

    setActiveBook(
        book
    );


    /* ---------------------------------------------------------
       ПЕРЕСТРАИВАЕМ СПИСОК ГЛАВ
       --------------------------------------------------------- */

    renderChapters(
        book
    );


    /* ---------------------------------------------------------
       ПОКАЗЫВАЕМ БОЛЬШОЙ ЗАГОЛОВОК
       --------------------------------------------------------- */

    renderChapterTitle(
        book,
        chapter
    );


    /* ---------------------------------------------------------
       ПОСЛЕ ПЕРЕРИСОВКИ ПРОВЕРЯЕМ
       ПОЛОЖЕНИЕ ЗАГОЛОВКА
       --------------------------------------------------------- */

    requestAnimationFrame(
        updateStickyChapterHeaderVisibility
    );


    /* ---------------------------------------------------------
       10.5. ФОРМИРУЕМ ПУТЬ К HTML-ФАЙЛУ
       --------------------------------------------------------- */

    const filePath =
        getChapterFilePath(
            book,
            chapter
        );


    /* ---------------------------------------------------------
       ДИАГНОСТИКА

       Можно увидеть:
       F12 → Console
       --------------------------------------------------------- */

    console.log(
        "ЗАГРУЖАЮ ФАЙЛ:",
        filePath
    );


    /* ---------------------------------------------------------
       10.6. ПОКАЗЫВАЕМ СООБЩЕНИЕ О ЗАГРУЗКЕ
       --------------------------------------------------------- */

    chapterText.innerHTML = `
        <p class="empty-chapter">
            Загрузка главы...
        </p>
    `;


    /* ---------------------------------------------------------
       10.7. ПЫТАЕМСЯ ЗАГРУЗИТЬ HTML
       --------------------------------------------------------- */

    try {


        /* -----------------------------------------------------
           FETCH

           cache: "no-store"
           не позволяет браузеру использовать
           устаревшую копию файла главы.
           ----------------------------------------------------- */

        const response =
            await fetch(
                filePath,
                {
                    cache: "no-store"
                }
            );


        /* -----------------------------------------------------
           HTTP STATUS

           200 = файл найден
           404 = файл не найден
           ----------------------------------------------------- */

        console.log(
            "HTTP STATUS:",
            response.status
        );


        /* -----------------------------------------------------
           10.8. ПРОВЕРЯЕМ ОТВЕТ СЕРВЕРА
           ----------------------------------------------------- */

        if (!response.ok) {

            throw new Error(
                `HTTP ${response.status}: ${filePath}`
            );

        }


        /* -----------------------------------------------------
           10.9. ЧИТАЕМ HTML КАК ТЕКСТ
           ----------------------------------------------------- */

        const html =
            await response.text();


        /* -----------------------------------------------------
           10.10. ВСТАВЛЯЕМ ГЛАВУ
           ----------------------------------------------------- */

        chapterText.innerHTML =
            html;


        /* -----------------------------------------------------
           10.11. УДАЛЯЕМ СТАРЫЙ ЗАГОЛОВОК

           Если внутри загружаемого файла
           сохранился:

               .chapter-heading

           он удаляется.

           Новый заголовок уже существует
           в reader.html.
           ----------------------------------------------------- */

        const oldChapterHeading =
            chapterText.querySelector(
                ".chapter-heading"
            );


        if (oldChapterHeading) {

            oldChapterHeading.remove();

        }


        /* -----------------------------------------------------
           ПОСЛЕ ЗАГРУЗКИ ЕЩЁ РАЗ ПРОВЕРЯЕМ
           ПОЛОЖЕНИЕ STICKY-ЗАГОЛОВКА
           ----------------------------------------------------- */

        requestAnimationFrame(
            updateStickyChapterHeaderVisibility
        );


        /* ---------------------------------------------------------
           10.12. ОБРАБОТКА ОШИБКИ
           --------------------------------------------------------- */

    } catch (error) {


        /* -----------------------------------------------------
           ПОДРОБНАЯ ОШИБКА В КОНСОЛИ
           ----------------------------------------------------- */

        console.error(
            "ОШИБКА ЗАГРУЗКИ:",
            error
        );


        /* -----------------------------------------------------
           СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЮ
           ----------------------------------------------------- */

        chapterText.innerHTML = `
            <p class="empty-chapter">
                Не удалось загрузить главу.
            </p>

            <p class="empty-chapter">
                Проверяемый файл:
            </p>

            <p class="empty-chapter">
                ${filePath}
            </p>
        `;

    }


    /* ---------------------------------------------------------
       10.13. ОБНОВЛЯЕМ URL

       Выполняется только если:

       pushState === true
       --------------------------------------------------------- */

    if (pushState) {


        const newUrl =
            `?book=${book}&chapter=${chapter}`;


        /* -----------------------------------------------------
           Добавляем адрес в историю браузера.

           Полная перезагрузка страницы
           при этом не происходит.
           ----------------------------------------------------- */

        history.pushState(
            {
                book,
                chapter
            },
            "",
            newUrl
        );

    }

}


